def _workflow(name: str) -> str:
    return (REPO_ROOT / ".github" / "workflows" / name).read_text(encoding="utf-8")


def test_the_hygiene_workflow_covers_pr_queue_and_main():
    text = _workflow("commit-hygiene.yml")
    for trigger in ("pull_request:", "merge_group:", "push:"):
        assert trigger in text, trigger
    assert "types: [opened, edited, reopened, synchronize]" in text  # body edits too
    assert "scripts/check_attribution.py" in text
    assert "fetch-depth: 0" in text  # the range needs the base commit
    assert "merge_group.base_sha" in text and "merge_group.head_sha" in text


