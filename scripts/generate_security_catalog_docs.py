"""Generate the public security-framework catalog reference from pinned data."""
from __future__ import annotations

import argparse
from pathlib import Path

from maverick.security_framework_catalog import (
    SECURITY_CATALOG_INDEX,
    SECURITY_CATALOG_PROVENANCE,
)

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "security-framework-catalog.md"


def _cell(value: str) -> str:
    return value.replace("|", r"\|").replace("\n", " ")


def render() -> str:
    """Render descriptions and counts from the validated catalog index."""
    lines = [
        "# Security framework catalogs",
        "",
        "This reference is generated by `python scripts/generate_security_catalog_docs.py`. "
        "Counts describe the pinned practices in Lightwork; they do not establish compliance.",
        "",
        "| Framework | Snapshot | Practices | Primary source | License and use |",
        "| --- | --- | ---: | --- | --- |",
    ]
    for name, rows in SECURITY_CATALOG_INDEX.items():
        source = SECURITY_CATALOG_PROVENANCE[name]
        lines.append(
            f"| {_cell(source['title'])} (`{name}`) | {_cell(source['version'])} | {len(rows)} | "
            f"[{_cell(source['source_artifact'])}]({source['source_url']}) | {_cell(source['license'])} |"
        )
    lines.extend([
        "",
        "CIS entries include safeguard identifiers and minimum Implementation Group assignments only. "
        "Consult an authorized copy for normative text and observe the license restrictions.",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report a stale generated file")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; rerun the generator")
            return 1
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
