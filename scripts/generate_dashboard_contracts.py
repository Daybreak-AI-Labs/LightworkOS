"""Generate shared dashboard schemas, client types, and replay fixtures.

Run from a development environment with maverick-dashboard installed:
    python scripts/generate_dashboard_contracts.py
Pass --check to detect generated files that no longer match the server models.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from maverick_dashboard.api_schemas import GoalEventOut, GoalEventsResponse, GoalOut

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_PATH = ROOT / "apps/client-contract-tests/contracts/dashboard-v1.json"
TYPE_PATHS = (
    ROOT / "apps/mobile-companion/src/generated/dashboard-contracts.ts",
    ROOT / "apps/vscode-extension/src/generated/dashboard-contracts.ts",
)
PYTHON_TYPES = ROOT / "sdks/python-client/lightwork_client/dashboard_contracts.py"
REPLAY_FIXTURE = ROOT / "apps/client-contract-tests/contracts/goal-events-v1.json"
KOTLIN_FIXTURE = ROOT / "apps/jetbrains-plugin/tests/GeneratedDashboardFixtures.kt"
MODELS = (GoalOut, GoalEventOut, GoalEventsResponse)


def _ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(_ts_type(branch) for branch in schema["anyOf"]))
    kind = schema.get("type")
    if kind in ("integer", "number"):
        return "number"
    if kind == "string":
        return "string"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        return f"Array<{_ts_type(schema.get('items', {}))}>"
    if kind == "object":
        values = schema.get("additionalProperties", {})
        return f"Record<string, {_ts_type(values) if isinstance(values, dict) else 'unknown'}>"
    return "unknown"


def _python_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(_python_type(branch) for branch in schema["anyOf"]))
    kind = schema.get("type")
    if kind == "integer":
        return "int"
    if kind == "number":
        return "float"
    if kind == "string":
        return "str"
    if kind == "boolean":
        return "bool"
    if kind == "null":
        return "None"
    if kind == "array":
        return f"list[{_python_type(schema.get('items', {}))}]"
    if kind == "object":
        values = schema.get("additionalProperties", {})
        return f"dict[str, {_python_type(values) if isinstance(values, dict) else 'Any'}]"
    return "Any"


def artifacts() -> dict[Path, str]:
    models = {model.__name__: model.model_json_schema() for model in MODELS}
    contract = json.dumps({"version": 1, "models": models}, indent=2, sort_keys=True) + "\n"
    lines = ["// Generated by scripts/generate_dashboard_contracts.py; do not edit.", ""]
    for name, schema in models.items():
        required = set(schema.get("required", []))
        lines.append(f"export type {name} = {{")
        for field, specification in schema["properties"].items():
            optional = "" if field in required else "?"
            lines.append(f"  {field}{optional}: {_ts_type(specification)};")
        lines.extend(["};", ""])
    typescript = "\n".join(lines)
    py = ["# Generated by scripts/generate_dashboard_contracts.py; do not edit.",
          "from __future__ import annotations", "", "from typing import Any, TypedDict", "", ""]
    for name, schema in models.items():
        required = set(schema.get("required", []))
        py.append(f"class _{name}Required(TypedDict):")
        for field, specification in schema["properties"].items():
            if field in required:
                py.append(f"    {field}: {_python_type(specification)}")
        if not required:
            py.append("    pass")
        py.extend(["", "", f"class {name}(_{name}Required, total=False):"])
        optional = {field: specification for field, specification in schema["properties"].items()
                    if field not in required}
        for field, specification in optional.items():
            py.append(f"    {field}: {_python_type(specification)}")
        if not optional:
            py.append("    pass")
        py.extend(["", ""])
    python_types = "\n".join(py).rstrip("\n") + "\n"
    replay = REPLAY_FIXTURE.read_text(encoding="utf-8")
    if '"""' in replay:
        raise ValueError("the Kotlin raw fixture cannot contain triple quotes")
    replay = replay.replace("$", "${'$'}")
    kotlin = ("// Generated by scripts/generate_dashboard_contracts.py; do not edit.\n"
              "package dev.maverick\n\ninternal val sharedGoalEventsFixture = \"\"\"\n"
              + replay + "\"\"\".trimIndent()\n")
    return {SCHEMA_PATH: contract, PYTHON_TYPES: python_types, KOTLIN_FIXTURE: kotlin,
            **dict.fromkeys(TYPE_PATHS, typescript)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        print("Dashboard contract artifacts are stale: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
